// - Nickname "หมามึน", has own FB page (518759411320762)
// - 18:00 daily dinner (TTS automation existed)
const sql = `-- Seed: TK (admin) + Luca the dog
-- Generated by scripts/seed-tk-luca.mjs — safe to re-run (INSERT OR IGNORE)
INSERT OR IGNORE INTO users (openId, email, name, passwordHash, loginMethod, role, createdAt, updatedAt, lastSignedIn)
VALUES ('${openId}', 'tripetkk@gmail.com', 'TK', '${hash}', 'email', 'admin', unixepoch(), unixepoch(), unixepoch());

INSERT OR IGNORE INTO pets (userId, name, breed, birthDate, photoUrl, gender, createdAt, updatedAt)
SELECT id, 'Luca', NULL, NULL, NULL, 'unknown', unixepoch(), unixepoch()
FROM users WHERE email = 'tripetkk@gmail.com'
AND NOT EXISTS (SELECT 1 FROM pets WHERE name = 'Luca' AND userId = users.id);

INSERT OR IGNORE INTO feeding_schedules (petId, foodType, amount, frequency, time, notes, createdAt, updatedAt)
SELECT id, 'standard', '', 'daily', '18:00', 'Luca dinner time — historical TTS automation fired at 18:00 daily', unixepoch(), unixepoch()
FROM pets WHERE name = 'Luca'
AND NOT EXISTS (SELECT 1 FROM feeding_schedules WHERE petId = pets.id);
`;

writeFileSync("drizzle/seed_tk_luca.sql", sql);
