/**
 * Seed TK as user + Luca as pet into the PetHealth D1 database.
 * Generates PBKDF2 hash using the same algorithm as server/_core/auth.ts.
 * Run: node scripts/seed-tk-luca.mjs <temp-password>
 * Output: drizzle/seed_tk_luca.sql (applied by deploy.sh after schema)
 */
import { webcrypto as crypto } from "node:crypto";
import { writeFileSync } from "node:fs";

const password = process.argv[2];
if (!password) {
  console.error("Usage: node scripts/seed-tk-luca.mjs <temp-password>");
  process.exit(1);
}

const encoder = new TextEncoder();

async function hashPassword(pw) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const keyMaterial = await crypto.subtle.importKey(
    "raw",
    encoder.encode(pw),
    "PBKDF2",
    false,
    ["deriveBits"]
  );
  const bits = await crypto.subtle.deriveBits(
    { name: "PBKDF2", salt, iterations: 100000, hash: "SHA-256" },
    keyMaterial,
    256
  );
  const toHex = (arr) => Array.from(arr).map(b => b.toString(16).padStart(2, "0")).join("");
  return `pbkdf2$100000$${toHex(salt)}$${toHex(new Uint8Array(bits))}`;
}

async function generateOpenId() {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  return Array.from(bytes).map(b => b.toString(16).padStart(2, "0")).join("");
}

const hash = await hashPassword(password);
const openId = await generateOpenId();

